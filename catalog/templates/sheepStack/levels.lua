function M.get(level)
  return M.levels[level]
end

function M.cards(level)
  local spec = M.get(level)
  local cards, layout = {}, layouts[spec.layout]
  local deck = {}
  -- 三轮错位发牌：同一类型的三张会落到不同锚点和不同层，而总数仍严格为三的倍数。
  for round = 1, 3 do
    for position = 1, #spec.kinds do
      local kind_index = ((position - 1) + (round - 1) * 2) % #spec.kinds + 1
      deck[#deck + 1] = spec.kinds[kind_index]
    end
  end
  for id, kind in ipairs(deck) do
    local round = math.floor((id - 1) / #layout) + 1
    local anchor = layout[(id - 1) % #layout + 1]
    local offset = shapes.row[round]
    -- order 是唯一的叠放权威：层号决定大层级，同层按创建顺序决定谁压在上方。
    cards[id] = { id = id, kind = kind, x = anchor[1] + offset[1], y = anchor[2] + offset[2], order = anchor[3] * 100 + id, taken = false }
  end
  return cards
end

return M
