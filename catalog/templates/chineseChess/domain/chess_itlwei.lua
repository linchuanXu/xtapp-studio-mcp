function M.value_at(ch, r, c)
  local piece = ch:lower():sub(1, 1)
  local table_for_piece = PIECE_SQUARE[piece]
  if not table_for_piece then return 0 end
  local red = ch:byte() >= 97
  local row = red and r or (9 - r)
  return table_for_piece[row + 1][c + 1]
end

function M.evaluate(board, side)
  local raw = 0
  for r = 0, 9 do
    for c = 0, 8 do
      local ch = State.at(board, r, c)
      if ch ~= "." then
        local value = M.value_at(ch, r, c)
        raw = raw + (ch:byte() >= 97 and value or -value)
      end
    end
  end
  return side == "r" and raw or -raw
end

return M
